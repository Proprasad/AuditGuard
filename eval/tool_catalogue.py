"""
Generate `docs/tool_catalogue.md` from the live FastMCP servers (audit AG-27).

    python -m eval.tool_catalogue          # rewrite the catalogue
    python -m eval.tool_catalogue --check  # exit 1 if the committed catalogue is stale

Lists, per tool: server, MCP safety annotations, the agent roles allowed to call it (RBAC allow-lists from
`src/guardrails/hooks.py`), input fields, whether a typed output schema is declared, and a schema hash so a
silent contract change shows up in review. `tests/test_audit_wave2.py` fails when the file is out of date.
"""

from __future__ import annotations

import asyncio
import hashlib
import importlib
import json
from pathlib import Path
import sys
from typing import Any

from fastmcp import Client

from src.guardrails.hooks import AGENT_TOOL_ALLOWLIST
from src.mcp_servers.client import _SERVERS

CATALOGUE_PATH = Path("docs/tool_catalogue.md")
_HINTS = ("readOnlyHint", "destructiveHint", "idempotentHint", "openWorldHint")


def _input_fields(schema: dict[str, Any]) -> list[str]:
    """Flatten the single `params` model most tools take into `name: type (required)` strings."""
    defs = schema.get("$defs", {})
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    if list(props) == ["params"] and "$ref" in props["params"]:
        target = defs.get(str(props["params"]["$ref"]).rsplit("/", 1)[-1], {})
        props, required = target.get("properties", {}), set(target.get("required", []))
    out = []
    for name, spec in props.items():
        kind = spec.get("type") or ("|".join(str(s.get("type", "ref")) for s in spec.get("anyOf", [])) or "object")
        out.append(f"`{name}`: {kind}{' (required)' if name in required else ''}")
    return out


async def collect_tools() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for server, module in _SERVERS.items():
        async with Client(importlib.import_module(module).mcp) as client:
            for tool in await client.list_tools():
                ann = tool.annotations.model_dump(exclude_none=True) if tool.annotations else {}
                contract = {"d": tool.description, "i": tool.inputSchema, "o": tool.outputSchema}
                rows.append(
                    {
                        "server": server,
                        "name": tool.name,
                        "description": (tool.description or "").strip(),
                        "annotations": ann,
                        "roles": sorted(r for r, allowed in AGENT_TOOL_ALLOWLIST.items() if tool.name in allowed),
                        "inputs": _input_fields(tool.inputSchema or {}),
                        "typed_output": bool(tool.outputSchema),
                        "schema_sha256": hashlib.sha256(json.dumps(contract, sort_keys=True).encode()).hexdigest()[:12],
                    }
                )
    return sorted(rows, key=lambda r: (r["server"], r["name"]))


def _hint_cell(ann: dict[str, Any]) -> str:
    if ann.get("readOnlyHint"):
        return "read-only"
    return "write, destructive" if ann.get("destructiveHint") else "write"


def render_catalogue(rows: list[dict[str, Any]]) -> str:
    lines = [
        "# MCP Tool Catalogue",
        "",
        "Generated by `python -m eval.tool_catalogue` from the live FastMCP servers. Do not edit by hand.",
        "",
        "| Server | Tool | Kind | Hints (readOnly / destructive / idempotent / openWorld) | Agent roles | Schema |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        hints = " / ".join("Y" if r["annotations"].get(h) else "N" for h in _HINTS)
        roles = ", ".join(f"`{x}`" for x in r["roles"]) or "none"
        lines.append(
            f"| {r['server']} | `{r['name']}` | {_hint_cell(r['annotations'])} | {hints} | {roles} "
            f"| `{r['schema_sha256']}` |"
        )
    for r in rows:
        lines += ["", f"## `{r['name']}` ({r['server']})", "", r["description"] or "(no description)", ""]
        lines.append("Inputs: " + ("; ".join(r["inputs"]) if r["inputs"] else "none"))
        lines.append("")
        lines.append(f"Typed output schema: {'yes' if r['typed_output'] else 'no'}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render_catalogue(asyncio.run(collect_tools()))
    if "--check" in argv:
        current = CATALOGUE_PATH.read_text(encoding="utf-8") if CATALOGUE_PATH.exists() else ""
        if current != text:
            sys.stderr.write(f"{CATALOGUE_PATH} is stale: run `python -m eval.tool_catalogue`\n")
            return 1
        return 0
    CATALOGUE_PATH.write_text(text, encoding="utf-8")
    sys.stdout.write(f"wrote {CATALOGUE_PATH} ({len(text.splitlines())} lines)\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
